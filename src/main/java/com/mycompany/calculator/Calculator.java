    private void OpAc(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_OpAc
        // TODO add your handling code here:
        if(edt_show.getText().length()>0){
            num1=Double.parseDouble(edt_show.getText());
        switch(evt.getActionCommand()){
            case"+":
               op ='+' ;
                lbl1.setText(num1 + "+");
                break;
            case"-":
                op ='-' ;
                lbl1.setText(num1 + "-");
                break;  
            case"×":
                op ='*' ;
                lbl1.setText(num1 + "×");
                break;    
            case"÷":
                op ='/' ;
                lbl1.setText(num1 + "÷");
                break;        
        }
        edt_show.setText("");
                
        }  
    }//GEN-LAST:event_OpAc

    private void b_equalActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_b_equalActionPerformed
        // TODO add your handling code here:
        if (edt_show.getText().length()>0){
            num2=Double.parseDouble(edt_show.getText());
        }else {
            num2=num1;
        }
        double r=0;
        
        if (op!='\u0000'){
            switch(op){
            case '+':
                    r=num1+num2;
                    break;  
            case '-':
                    r=num1-num2;
                    break;  
            case '*':
                    r=num1*num2;
                    break;  
            case '/':
                    r=num1/num2;
                    break;          
        }
        edt_show.setText(String.valueOf(r));
        lbl1.setText(lbl1.getText()+num2+"=");
        op='\u0000';
        }else{
            edt_show.setText(num2+"");
        }
            
        
            
        
    }//GEN-LAST:event_b_equalActionPerformed

